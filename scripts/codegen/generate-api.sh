set -e

if [[ "$OSTYPE" == "darwin"* ]]
then
       READLINK=greadlink
else
       READLINK=readlink
fi

HERE=$(dirname "$($READLINK --canonicalize "$BASH_SOURCE")")
. "$HERE/../lib/_trap"

ROOT=$($READLINK --canonicalize "$HERE/../..")

PORCH_API_DIR=$ROOT/api
PORCH_API_GENERATED_DIR=$ROOT/api/generated

BOILERPLATE=$ROOT/scripts/boilerplate.go.txt
OPENAPI_REPORT=$ROOT/gen_openapi.report

KUBERNETES_VERSION=0.37.0
go get "k8s.io/code-generator@v$KUBERNETES_VERSION"
CODE_GENERATOR=$(go list -f '{{.Dir}}' -m "k8s.io/code-generator@v$KUBERNETES_VERSION")
. "${CODE_GENERATOR}/kube_codegen.sh"

cd "$PORCH_API_DIR"

# kpt/api and kyaml types are not tagged for openapi-gen. Copy those modules,
# inject +k8s:openapi-gen tags, and replace them only for this generation so
# --extra-pkgs emits schemas for github.com/kptdev/kpt/api/kptfile/v1 (the whole
# package, including RenderStatus) plus fnresult/v1 and the nested kyaml types.
# kyaml is tagged per-type so the rest of that package is not emitted.
copy_module_overlay() {
	local src="$1"
	local dest="$2"
	mkdir -p "$dest"
	cp -a "$src/." "$dest/"
	chmod -R u+w "$dest"
}

# gengo only reads package-level +k8s:openapi-gen from a file named doc.go.
write_package_openapi_gen_doc() {
	local dir="$1"
	local pkg="$2"
	cat >"${dir}/doc.go" <<EOF
// +k8s:openapi-gen=true
package ${pkg}
EOF
}

inject_type_openapi_gen_tag() {
	local file="$1"
	local type_name="$2"
	python3 - "$file" "$type_name" <<'PY'
import pathlib, re, sys
path = pathlib.Path(sys.argv[1])
type_name = sys.argv[2]
text = path.read_text()
if re.search(rf"// \+k8s:openapi-gen=true\ntype {type_name} ", text):
    sys.exit(0)
new, n = re.subn(rf"(type {type_name} )", r"// +k8s:openapi-gen=true\n\1", text, count=1)
if n != 1:
    sys.exit(f"failed to inject type openapi-gen tag for {type_name} in {path}")
path.write_text(new)
PY
}

echo 'gen_helpers...'

kube::codegen::gen_helpers \
	"." \
	--boilerplate "$BOILERPLATE" \
	--extra-peer-dir "k8s.io/apimachinery/pkg/apis/meta/v1" \
	--extra-peer-dir "k8s.io/apimachinery/pkg/runtime" \
	--extra-peer-dir "k8s.io/apimachinery/pkg/version"

# kube::codegen::gen_helpers deletes every zz_generated.deepcopy.go under api/
# and only regenerates packages tagged for deepcopy-gen (porch, porch/v1alpha1).
# CRD packages (porchconfig, porch/v1alpha2) are generated by controller-gen.
echo 'Generating controller-gen object deepcopy for CRD packages...'
YEAR_GEN=${YEAR_GEN:-$(date '+%Y')}
go run sigs.k8s.io/controller-tools/cmd/controller-gen@v0.22.0 \
	"object:headerFile=${BOILERPLATE},year=${YEAR_GEN}" \
	"paths={./porchconfig/...,./porch/v1alpha2/...}"

echo 'gen_openapi...'

KPT_API_SRC=$(go list -f '{{.Dir}}' -m github.com/kptdev/kpt/api)
KYAML_SRC=$(go list -f '{{.Dir}}' -m sigs.k8s.io/kustomize/kyaml)
KPT_OPENAPI_OVERLAY=$(mktemp -d)
KYAML_OPENAPI_OVERLAY=$(mktemp -d)
API_GOMOD_BACKUP=$(mktemp)
API_GOSUM_BACKUP=$(mktemp)
cp go.mod "$API_GOMOD_BACKUP"
cp go.sum "$API_GOSUM_BACKUP"

copy_module_overlay "$KPT_API_SRC" "$KPT_OPENAPI_OVERLAY"
copy_module_overlay "$KYAML_SRC" "$KYAML_OPENAPI_OVERLAY"
write_package_openapi_gen_doc "$KPT_OPENAPI_OVERLAY/kptfile/v1" v1
write_package_openapi_gen_doc "$KPT_OPENAPI_OVERLAY/fnresult/v1" v1
inject_type_openapi_gen_tag "$KYAML_OPENAPI_OVERLAY/yaml/types.go" TypeMeta
inject_type_openapi_gen_tag "$KYAML_OPENAPI_OVERLAY/yaml/types.go" NameMeta
inject_type_openapi_gen_tag "$KYAML_OPENAPI_OVERLAY/yaml/types.go" ResourceMeta
inject_type_openapi_gen_tag "$KYAML_OPENAPI_OVERLAY/yaml/types.go" ObjectMeta
inject_type_openapi_gen_tag "$KYAML_OPENAPI_OVERLAY/yaml/types.go" ResourceIdentifier
inject_type_openapi_gen_tag "$KYAML_OPENAPI_OVERLAY/fn/framework/result.go" File

go mod edit -replace "github.com/kptdev/kpt/api=${KPT_OPENAPI_OVERLAY}"
go mod edit -replace "sigs.k8s.io/kustomize/kyaml=${KYAML_OPENAPI_OVERLAY}"

KUBE_CODEGEN_READONLY_PKGS+=(
	github.com/kptdev/kpt/api/kptfile/v1
	github.com/kptdev/kpt/api/fnresult/v1
	sigs.k8s.io/kustomize/kyaml/yaml
	sigs.k8s.io/kustomize/kyaml/fn/framework
)

openapi_status=0
kube::codegen::gen_openapi \
	"." \
	--output-dir "$PORCH_API_GENERATED_DIR/openapi" \
	--output-pkg "github.com/kptdev/porch/api/generated" \
	--output-model-name-file "zz_generated.model_name.go" \
	--boilerplate "$BOILERPLATE" \
	--report-filename "$OPENAPI_REPORT" \
	--update-report \
	--extra-pkgs github.com/kptdev/kpt/api/kptfile/v1 \
	--extra-pkgs github.com/kptdev/kpt/api/fnresult/v1 \
	--extra-pkgs sigs.k8s.io/kustomize/kyaml/yaml \
	--extra-pkgs sigs.k8s.io/kustomize/kyaml/fn/framework \
	|| openapi_status=$?

cp "$API_GOMOD_BACKUP" go.mod
cp "$API_GOSUM_BACKUP" go.sum
rm -rf "$KPT_OPENAPI_OVERLAY" "$KYAML_OPENAPI_OVERLAY" "$API_GOMOD_BACKUP" "$API_GOSUM_BACKUP"
if [ "$openapi_status" -ne 0 ]; then
	exit "$openapi_status"
fi

echo 'gen_client...'

kube::codegen::gen_client \
	"." \
	--output-dir "$PORCH_API_GENERATED_DIR" \
	--with-watch \
	--output-pkg "github.com/kptdev/porch/api/generated" \
	--plural-exceptions "PackageRevisionResources:PackageRevisionResources" \
	--boilerplate "$BOILERPLATE"

# Our "go get" added dependencies that we don't need
cd "$ROOT"
go mod tidy
